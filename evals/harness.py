"""Shared machinery for the eval suite: load fixtures, run them, keep the trace.

Fixtures are replayed through exactly the same path the live console uses — the
WebSocket turn loop in ``SessionRunner`` — so what the gates measure is what a
judge would see, not a shortcut through the internals.
"""

from __future__ import annotations

import asyncio
import json
import os
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from slr.config import Settings, get_settings
from slr.retrieval.store import load_index
from slr.stream.engine import Engine, SessionRunner

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "evals" / "fixtures"

#: fixture folder -> what that family is for
#: Folders are shared by both corpora; a fixture's ``corpus`` field says which
#: index it runs against. ASQA fixtures are generated by evals/build_dataset.py.
FAMILIES = {
    "compound": "compound utterances (G2, G3, G4)",
    "late_detail": "late-arriving constraints (G5)",
    "suppression": "presentation-only turns (G2 false triggers)",
    "single": "single-intent controls (over-fragmentation)",
    "unanswerable": "questions the corpus cannot answer (G4 uncertainty)",
}


@dataclass
class TurnRun:
    fixture: str
    corpus: str
    family: str
    index: int
    expect: dict[str, Any]
    trace: dict[str, Any]
    events: list[dict[str, Any]]

    @property
    def answer(self) -> str:
        return "".join(e["text"] for e in self.events if e["type"] == "answer.token")

    def of(self, kind: str) -> list[dict[str, Any]]:
        return [e for e in self.events if e["type"] == kind]


@dataclass
class RunResult:
    turns: list[TurnRun] = field(default_factory=list)
    seconds: float = 0.0
    settings: dict[str, Any] = field(default_factory=dict)
    models: dict[str, str] = field(default_factory=dict)

    def family(self, *names: str) -> list[TurnRun]:
        return [t for t in self.turns if t.family in names]


def load_fixtures(corpus: str, families: list[str] | None = None) -> list[dict[str, Any]]:
    out = []
    for folder in sorted(FIXTURES.iterdir()):
        if not folder.is_dir():
            continue
        if families and folder.name not in families:
            continue
        for path in sorted(folder.glob("*.json")):
            data = json.loads(path.read_text(encoding="utf-8"))
            if data.get("corpus") != corpus:
                continue
            data["family"] = folder.name
            out.append(data)
    return out


def build_engine(settings: Settings) -> Engine:
    return Engine.from_settings(settings, load_index(settings.index_dir))


async def run_fixtures(engine: Engine, fixtures: list[dict[str, Any]], speed: float = 8.0) -> RunResult:
    result = RunResult(settings=_knobs(engine.s), models=engine.models_info())
    started = time.perf_counter()
    for fixture in fixtures:
        events: list[dict[str, Any]] = []

        async def emit(event: dict[str, Any]) -> None:
            events.append(event)

        runner = SessionRunner(engine, emit)
        await runner.start()
        # One session per fixture: session state is per conversation, and a
        # fixture's later turns depend on its own earlier ones only.
        await runner.play_turns(fixture["turns"], speed)
        for i, (spec, trace) in enumerate(zip(fixture["turns"], runner.completed)):
            turn_events = [e for e in events if e.get("turnId") == trace["turn_id"]]
            result.turns.append(
                TurnRun(
                    fixture=fixture["id"],
                    corpus=fixture.get("corpus", "enterprise"),
                    family=fixture["family"],
                    index=i,
                    expect=spec.get("expect", {}),
                    trace=trace,
                    events=turn_events,
                )
            )
        await runner.close()
    await engine.aclose()
    result.seconds = time.perf_counter() - started
    return result


def run(engine: Engine, fixtures: list[dict[str, Any]], speed: float = 8.0) -> RunResult:
    return asyncio.run(run_fixtures(engine, fixtures, speed))


def _knobs(s: Settings) -> dict[str, Any]:
    return {
        "controller": s.controller,
        "branches": ",".join(s.branches),
        "quota_per_intent": s.quota_per_intent,
        "top_k": s.top_k,
        "tau_stab": s.tau_stab,
        "stab_run": s.stab_run,
        "merge_cos": s.merge_cos,
        "support_min": s.support_min,
        "llm": s.llm,
        "reranker": s.rerank_model if s.reranker != "none" else "none",
    }


def asqa_dir() -> Path:
    """Holds the ASQA corpus (``corpus/``) and its index (``index_asqa/``).

    Overridable so a container can keep both on a volume.
    """
    return Path(os.environ.get("SLR_ASQA_DIR") or (ROOT / "data"))


def settings_for(corpus: str, **overrides) -> Settings:
    """Settings pointed at one of the two dev corpora."""
    base = get_settings()
    if corpus == "asqa":
        root = asqa_dir()
        base = base.with_overrides(corpus_dir=str(root / "corpus"), index_dir=str(root / "index_asqa"))
    return base.with_overrides(**overrides) if overrides else base


def ensure_asqa_corpus() -> dict:
    """Build the ASQA corpus from the vendored snapshot if it is missing.

    A fresh clone has the snapshot, gold labels and fixtures but not the
    corpus, and `make eval` must not ask anyone to run a second command first.
    The build is seeded, so the fixtures it rewrites are byte-identical.
    """
    from evals.build_dataset import DEFAULT_COUNTS, build

    corpus = asqa_dir() / "corpus"
    if corpus.is_dir() and any(corpus.glob("*.md")):
        return {"asqa_corpus": "reused"}
    info = build(DEFAULT_COUNTS, corpus_out=corpus)
    return {"asqa_corpus": f"built from the vendored snapshot ({info['corpus']})"}


def ensure_index(settings: Settings) -> None:
    if not (Path(settings.index_dir) / "manifest.json").exists():
        from slr.ingest.build_index import build

        build(settings.corpus_dir, settings.index_dir)
