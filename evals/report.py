"""results JSON -> docs/BENCHMARK_REPORT.md.

Every number in the report comes from the payload; the prose around a failure
names the mechanism but never invents the measurement.
"""

from __future__ import annotations

import datetime as dt
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "docs" / "BENCHMARK_REPORT.md"

EDGE_EXPLANATION = {
    "late_trigger": (
        "The controller waits for content sufficiency and either semantic stability or a closed clause. "
        "A short utterance can end before any of those fire, so retrieval starts at the utterance end. "
        "This is the deliberate side of the trade: lowering the bar buys earlier retrieval and pays for it "
        "in searches on incomplete thoughts."
    ),
    "starved_sub_intent": (
        "A sub-intent reached synthesis with no evidence of its own. With the per-intent quota on this is "
        "usually a retrieval miss rather than a fusion one: the sub-query returned nothing above the margin cut."
    ),
    "under_decomposition": (
        "Fewer sub-queries than gold sub-intents. Two different causes hide behind one symptom. On a request that "
        "bundles several asks it is a missed split: the clause splitter found no boundary, usually because the "
        "speaker used no punctuation and no conjunction that opens a new request. On an ASQA question it is not a "
        "parsing failure at all. 'Who has the highest goals in world football' has no second clause to find, and "
        "enumerating its readings (men's, women's, all-time) needs knowledge of the domain, which the deterministic "
        "splitter lacks and a language model has. This is where the model-backed decomposer earns its cost."
    ),
    "over_fragmentation": (
        "More sub-queries than gold sub-intents — the failure the merge guard and the cap exist to bound. "
        "Extra near-duplicate queries dilute the reranker's budget and buy nothing."
    ),
    "claim_withheld": (
        "The grounding verifier could not support a generated sentence from its cited chunk, so the sentence "
        "was withheld and reported as uncertainty instead of shipped. That is the intended behaviour, but each "
        "case is worth reading: a conservative verifier costs recall of true statements."
    ),
    "false_trigger": (
        "A presentation-only turn issued a vector query before the suppression signal resolved — the controller "
        "sees a prefix, and 'shorten' can arrive after content words do."
    ),
}


def _fmt(value: Any) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:g}"
    return str(value)


def _recall(arm: dict[str, Any]) -> str:
    if arm.get("recall_at_k_pct") is None:
        return "—"
    return f"{_fmt(arm['recall_at_k_pct'])}% ({arm.get('recall_unit', 'passages')})"


def _gate_table(rows: list[dict[str, Any]]) -> list[str]:
    out = ["| Gate | Criterion | Measured | Threshold | Result |", "|---|---|---|---|---|"]
    for g in rows:
        unit = "" if g["value"] is None else ("%" if g["id"] != "G1" else "")
        if not g.get("applicable", True):
            verdict = f"n/a — {g.get('note', 'not exercised by this corpus')}"
        else:
            verdict = "**PASS**" if g["passed"] else "**FAIL**"
        out.append(f"| {g['id']} | {g['name']} | {_fmt(g['value'])}{unit} | {g['threshold']} | {verdict} |")
    return out


def write_report(payload: dict[str, Any], path: Path = REPORT) -> Path:
    gates = payload["gates"]
    engine = payload["engine"]
    generated = dt.datetime.fromtimestamp(payload["generated_at"] / 1000).strftime("%Y-%m-%d %H:%M")
    lines: list[str] = []
    add = lines.append

    add("# Benchmarking & Evaluation Report")
    add("")
    add("**Streaming Live RAG — Samsung PRISM GenAI Hackathon, Theme 04**")
    add("")
    add(f"Generated by `make eval` at {generated}. Every number below is measured from that run; ")
    add("nothing is hand-entered. Re-running the command overwrites this file.")
    add("")
    add("## 1. Run configuration")
    add("")
    add("| | |")
    add("|---|---|")
    for key, value in engine.get("models", {}).items():
        add(f"| {key} | `{value}` |")
    add(f"| LLM configured | {'yes' if engine.get('llm_configured') else 'no — deterministic offline arms'} |")
    add(f"| replay speed | {engine.get('replay_speed')}x |")
    for key, value in engine.get("knobs", {}).items():
        add(f"| {key} | `{value}` |")
    add("")
    for corpus, info in payload.get("corpora", {}).items():
        add(f"- **{corpus}** corpus: {info['documents']} documents, {info['chunks']} chunks")
    add("")
    add(f"Total wall clock: {payload['seconds']}s.")
    add("")

    add("## 2. Acceptance gates")
    add("")
    for corpus, rows in gates.items():
        add(f"### {corpus} corpus")
        add("")
        lines.extend(_gate_table(rows))
        add("")
        for g in rows:
            if g["id"] == "G2":
                d = g["detail"]
                add(
                    f"- G2 detail: {d['retrieved_before_end']}/{d['eligible_turns']} turns that should retrieve began "
                    f"retrieving before the utterance ended (the end-of-speech signal); median lead "
                    f"**{_fmt(d['median_lead_ms'])} ms**, max {_fmt(d['max_lead_ms'])} ms. Stricter: "
                    f"{_fmt(d.get('before_last_word_pct'))}% began before the last word was spoken; the rest fired on "
                    f"the final words, in the pause before the end signal. False-trigger rate on the "
                    f"{d['suppression_turns']} turns that should not retrieve: {_fmt(d['false_trigger_rate_pct'])}%."
                )
            if g["id"] == "G3":
                d = g["detail"]
                add(
                    f"- G3 detail: {d['identified']}/{d['compound_utterances']} compound utterances isolated two or more "
                    f"sub-intents; full coverage of every gold intent {_fmt(d['full_coverage_pct'])}%; "
                    f"over-fragmentation {_fmt(d['over_fragmentation_pct'])}%; single-intent utterances kept single "
                    f"{_fmt(d['single_intent_kept_single_pct'])}%."
                )
                if d.get("by_family"):
                    add(f"  - by fixture family: {d['by_family']}")
            if g["id"] == "G4":
                d = g["detail"]
                add(
                    f"- G4 detail: support is pooled over every factual sentence the model wrote: "
                    f"{_fmt(d.get('claims_supported'))} of {_fmt(d.get('claims_written'))} verified (a withheld "
                    f"sentence counts against it even though it never reached the user); per-turn mean "
                    f"{_fmt(d.get('per_turn_mean_support_pct'))}%. {d['total_claims']} claims shipped across "
                    f"{d['turns_with_claims']} answered turns; **{d['fabricated_citations']} fabricated citations "
                    f"shipped**, {d['fabricated_blocked_before_shipping']} blocked before shipping; "
                    + (f"recall@k (gold passages) {_fmt(d['recall_at_k_pct'])}% over {d['recall_samples']} labelled turns; "
                       if d.get("recall_samples") else "")
                    + (f"recall@k (gold documents) {_fmt(d.get('doc_recall_at_k_pct'))}% over "
                       f"{d.get('doc_recall_samples')} labelled turns; " if d.get("doc_recall_samples") else "")
                    + f"{d['turns_flagging_uncertainty']} turns flagged uncertainty."
                )
                if d.get("shipped_claims_checked"):
                    add(
                        f"- G4 independent audit: a second NLI model the engine never uses (`{d['auditor']}`) "
                        f"re-read the {d['shipped_claims_checked']} shipped claims against the chunks they cite and "
                        f"agreed with {_fmt(d['shipped_claims_supported_pct'])}% of them."
                    )
                    for ex in d.get("shipped_claims_failing_examples", [])[:5]:
                        add(f"  - `{ex['fixture']}` (support {ex['support']}): {ex['claim']}")
            if g["id"] == "G5":
                d = g["detail"]
                for row in d["rows"]:
                    add(
                        f"- G5 `{row['fixture']}`: v{_fmt(row['version'])} from v{_fmt(row['parent'])}, "
                        f"{row['preserved']} claims preserved, {row['mutated']} rewritten, "
                        f"full-corpus search `{row['full_corpus_search']}`, "
                        f"{row['carried_from_session']} chunks carried from session state"
                        + (" (the parent answer verified no claims, so none could be kept)."
                           if row.get("parent_claims") == 0 else ".")
                    )
            if g["id"] == "G6" and g["detail"]["incomplete"]:
                add(f"- G6 incomplete traces: {g['detail']['incomplete']}")
        add("")

    add("## 3. Latency and cost")
    add("")
    add("| Corpus | Turns | Retrieval lead (median) | TTFT (median) | TTFT p90 | Turn complete (median) | Cost/turn | Tokens/turn |")
    add("|---|---|---|---|---|---|---|---|")
    for corpus, perf in payload.get("performance", {}).items():
        add(
            f"| {corpus} | {perf['turns']} | {_fmt(perf['retrieval_lead_ms']['median'])} ms | "
            f"{_fmt(perf['time_to_first_token_ms']['median'])} ms | {_fmt(perf['time_to_first_token_ms']['p90'])} ms | "
            f"{_fmt(perf['turn_complete_ms']['median'])} ms | ${_fmt(perf['cost_per_turn_usd']['mean'])} | "
            f"{_fmt(perf['tokens_per_turn']['mean'])} |"
        )
    add("")
    add("Retrieval lead is measured from the trace: `utterance_end_ms - first_retrieval_ms`. ")
    add("TTFT is measured from the end of the utterance to the first *validated* token, because the engine ")
    add("releases a sentence only after its citations resolve and its support clears the bar.")
    add("")

    add("## 4. Against a baseline pipeline")
    add("")
    add(
        "The baseline is a conventional RAG turn on the same fixtures, with the same retriever, reranker, "
        "synthesiser and verifier: nothing happens while the user speaks, then the whole utterance is one "
        "search (`SLR_CONTROLLER=batch`, `SLR_DECOMPOSE=off`). It has no notion of a presentation-only turn "
        "or of a late detail, so it searches on both. The difference between the rows is exactly what "
        "streaming, decomposition and session refinement add."
    )
    add("")
    if not payload.get("baseline"):
        add("_Not run._")
        add("")
    for corpus, pair in (payload.get("baseline") or {}).items():
        add(f"### {corpus} corpus")
        add("")
        add(
            "| Pipeline | Retrieval before speech ends | Searches on reformat turns | Multi-intent (G3) | "
            "Late detail refined, not restarted (G5) | Citation support | Recall@k | Fabricated | "
            "TTFT after speech | Answer complete after speech | Cost/turn |"
        )
        add("|---|---|---|---|---|---|---|---|---|---|---|")
        for key in ("ours", "baseline"):
            arm = pair[key]
            add(
                f"| {arm['arm']} | {_fmt(arm['early_retrieval_pct'])}% | {_fmt(arm['false_trigger_pct'])}% | "
                f"{_fmt(arm['multi_intent_pct'])}% | {_fmt(arm['refined_not_restarted_pct'])}% | "
                f"{_fmt(arm['citation_support_pct'])}% | {_recall(arm)} | "
                f"{_fmt(arm['fabricated_citations'])} | {_fmt(arm['median_ttft_ms'])} ms | "
                f"{_fmt(arm['median_complete_ms'])} ms | ${_fmt(arm['mean_cost_usd'])} |"
            )
        add("")

    if payload.get("ablations"):
        add("## 5. Ablations")
        add("")
        for exp in payload["ablations"]:
            add(f"### {exp['experiment']}")
            add("")
            add(f"_{exp['question']}_")
            add("")
            add("| Arm | Early retrieval | Multi-intent | Citation support | Recall@k | Intents with evidence | TTFT | Cost/turn |")
            add("|---|---|---|---|---|---|---|---|")
            for arm in exp["arms"]:
                if arm.get("skipped"):
                    add(f"| {arm['arm']} | _{arm['skipped']}_ | | | | | | |")
                    continue
                cov = arm["intent_coverage"]
                add(
                    f"| {arm['arm']} | {_fmt(arm['early_retrieval_pct'])}% | {_fmt(arm['multi_intent_pct'])}% | "
                    f"{_fmt(arm['citation_support_pct'])}% | {_recall(arm)} | "
                    f"{_fmt(cov['with_evidence_pct'])}% ({cov['starved']} starved) | "
                    f"{_fmt(arm['median_ttft_ms'])} ms | ${_fmt(arm['mean_cost_usd'])} |"
                )
            add("")
            starved = [a for a in exp["arms"] if not a.get("skipped") and a["intent_coverage"]["starved_examples"]]
            for arm in starved:
                add(f"- `{arm['arm']}` left these sub-intents without evidence: ")
                for ex in arm["intent_coverage"]["starved_examples"]:
                    add(f"  - {ex['fixture']}: \"{ex['sub_query']}\"")
            add("")

    add("## 6. Analysed edge-case failures")
    add("")
    cases = payload.get("edge_cases", [])
    if not cases:
        add("No failures were observed in this run.")
    else:
        by_category: dict[str, list[dict[str, Any]]] = {}
        for case in cases:
            by_category.setdefault(case["category"], []).append(case)
        plural = "category" if len(by_category) == 1 else "categories"
        add(f"{len(cases)} failure instances across {len(by_category)} {plural}, all taken from the run above.")
        add("")
        for n, (category, items) in enumerate(sorted(by_category.items(), key=lambda kv: -len(kv[1])), start=1):
            first = items[0]
            add(f"### {n}. {category.replace('_', ' ')} ({len(items)} instance{'s' if len(items) != 1 else ''})")
            add("")
            add(f"**Example** — `{first['fixture']}` ({first['corpus']} corpus)")
            add("")
            add(f"> {first['utterance']}")
            add("")
            add(f"**What happened.** {first['what_happened']}")
            add("")
            add(f"**Why.** {EDGE_EXPLANATION.get(category, 'See the trace record for the mechanism.')}")
            add("")
            add(f"**Trace evidence.** `{first['evidence']}`")
            add("")
            if len(items) > 1:
                add(f"Other instances: {', '.join(sorted({i['fixture'] for i in items[1:]})[:8])}")
                add("")

    add("## 7. Reproducing this")
    add("")
    add("```bash")
    add("docker compose up --build      # or: make up")
    add("make eval                      # rebuilds any missing index, runs every fixture, rewrites this file")
    add("```")
    add("")
    add("Fixtures live in `evals/fixtures/`, corpora in `evals/corpora/` and `data/corpus/` (ASQA, built by `make dataset`). ")
    add("`evals/results/latest.json` holds the full payload this report was rendered from, ")
    add("including every per-turn trace field the gates read.")
    add("")

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
